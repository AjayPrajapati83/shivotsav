export const getEventsByTier = (tier) => {
  if (tier === 'all') return events;
  return events.filter((e) => e.tier === tier);
};

export const getCategoryColor = (category) => {
  const map = {
    'Performing Arts': 'var(--color-cat-performing)',
    'Fine Arts': 'var(--color-cat-finearts)',
    'Literary Arts': 'var(--color-cat-literary)',
    'Informals': 'var(--color-cat-informals)',
    'Gaming & Sports': 'var(--color-cat-gaming)',
  };
  return map[category] || 'var(--color-gold-400)';
};

export const getTierLabel = (tier) => {
  return tier.charAt(0).toUpperCase() + tier.slice(1);
};

